// Язык интерфейса: английский и русский.
//
// Плагин выложен публично, а весь его интерфейс был русским — окно настроек,
// панель внутри Premiere и диагностический отчёт, который люди прикладывают
// к issue. Английский тут не украшение, а условие, чтобы отчёт вообще можно
// было прочитать со стороны.
//
// ⚠ ГЛАВНОЕ ПРАВИЛО, И ОНО НЕ ФОРМАЛЬНОСТЬ.
//
// Tr возвращает ЦЕЛУЮ строку и никогда не возвращает строку формата.
// Ни при каких обстоятельствах результат Tr не попадает первым аргументом
// в printf-подобную функцию:
//
//     Format(Tr(L"%d files", L"файлов: %d"), n)     // НЕЛЬЗЯ
//     out << Tr(L"files: ", L"файлов: ") << n;      // так
//
// Причина известна на опыте: локализация диагностики уже была написана
// однажды именно через Format(Tr(...)) и откачена вместе с падением, которое
// так и не объяснили. Два языка обязаны совпадать по числу и порядку
// %-подстановок, иначе printf читает чужой стек; расходятся они молча и
// на редкой ветке, где никто не смотрит. Числа собираются потоком
// (wostringstream), и тогда расходиться нечему в принципе.
//
// Отсюда же следствие: в таблице ниже нет ни одной строки с '%'.

#pragma once

#include <string>

namespace aether {

enum class Language {
    English,
    Russian,
};

// Что выбрано в настройках: `lang = auto | ru | en`.
//
// auto решает по языку интерфейса Windows: русский — русский, всё
// остальное — английский. Английский тут запасной вариант для мира,
// а не «главный» язык.
Language DetectLanguage();

// Разобрать строку из настроек или из --lang. Неизвестное значение
// (и пустое) означает auto.
Language ParseLanguage(const wchar_t* code);

// То же для узкой строки: настройки хранят язык в std::string, и заводить
// ради одного вызова преобразование в широкую — лишний шаг, на котором
// нечему пойти не так, но который всё равно придётся написать дважды.
Language ParseLanguage(const char* code);

// Двухбуквенный код обратно — для записи в настройки и для отчёта.
const wchar_t* LanguageCode(Language language);

void     SetLanguage(Language language);
Language CurrentLanguage();

// Выбор строки по текущему языку. Порядок аргументов — английский первым,
// потому что он же по умолчанию.
inline const wchar_t* Tr(const wchar_t* english, const wchar_t* russian)
{
    return CurrentLanguage() == Language::Russian ? russian : english;
}

// То же для узких строк — их немного, но они есть (имена кодеков, JSON).
inline const char* TrA(const char* english, const char* russian)
{
    return CurrentLanguage() == Language::Russian ? russian : english;
}

} // namespace aether
