// Настройки плагина, общие для всех файлов.
//
// Живут в %LOCALAPPDATA%\Aether\settings.ini, а не рядом с плагином: папка
// плагина лежит в Program Files и требует администратора на каждую запись.
// Переключать декодер человек должен без этого.
//
// (Старое имя папки — AV1Importer. Настройка из неё переносится один раз
// при первом обращении, см. SettingsFolder в .cpp.)
//
// Своего окна внутри Premiere у импортёра нет намеренно. SDK предлагает два
// пути, и оба хуже: окно по imGetPrefs8 всплывает при импорте каждого файла
// либо перехватывает двойной щелчок по клипу, а панель настроек как у RED
// требует отдельного плагина-эффекта и привязана к клипу, а не к плагину.
// К тому же настройка нужна ровно тогда, когда Premiere из-за драйвера
// не запускается — внутри него она была бы недоступна.
//
// Переключается программой Aether.exe (ярлык в меню «Пуск») и панелью
// Window -> Extensions внутри Premiere. Обе правят один и тот же файл
// через эту реализацию, а не через второй парсер.

#pragma once

#include <cstdint>
#include <string>

namespace av1imp {

enum class DecodeMode {
    Auto = 0,     // выбрать по числу ядер, см. PreferHardware()
    Software,     // всегда процессор
    Hardware,     // всегда видеокарта
};

struct Settings {
    bool     enabled         = true;
    DecodeMode decode        = DecodeMode::Auto;
    uint32_t memoryCacheMB   = 512;
    // Включается пользователем до живого cold/warm замера в Premiere.
    bool     previewCache    = false;
    uint32_t previewCacheMB  = 2048;

    // Язык интерфейса: "auto", "ru" или "en". Пустая строка равна "auto".
    //
    // Хранится строкой, а не перечислением, и это осознанно: само ЯДРО про
    // языки ничего не знает и знать не должно — оно не показывает ни одной
    // надписи. Здесь лежит только выбор человека, а разбирают его окно,
    // диагностика и панель, у которых надписи есть (см. tools/localization.h).
    // Так «auto» доживает до них неиспорченным: разверни мы его тут в ru/en,
    // выбор «как в системе» превратился бы в жёсткий язык при первом же
    // сохранении настроек.
    std::string language     = "auto";
};

// Папка, из которой загружен плагин, с завершающим слэшем.
// Рядом лежат библиотеки ffmpeg. Доступно только внутри плагина.
const wchar_t* PluginDirectory();

// Только журнал, без ffmpeg. Нужен выключенному импортёру: Adobe всё равно
// зовёт imInit, а грузить библиотеки в этом случае незачем.
void EnsureLog();

// Отложенная подготовка: журнал и библиотеки ffmpeg. Вызывается из точки входа
// плагина, а не при загрузке DLL, — см. длинный комментарий в AV1Runtime.cpp.
// Звать можно сколько угодно раз, работа делается один раз. false означает,
// что обязательные DLL не загрузились и обращаться к ffmpeg небезопасно.
bool EnsureRuntime();

// Полный путь к файлу настроек. Папка создаётся при сохранении.
const wchar_t* SettingsFilePath();

Settings CurrentSettings();
bool SaveSettings(const Settings& settings);

uint64_t MemoryCacheLimitBytes();
bool PluginEnabled();

std::string SettingsJson();

// Что выбрано сейчас. Переменная среды AV1IMPORTER_HARDWARE (0/1) главнее файла:
// ею удобно проверить догадку, ничего не сохраняя.
DecodeMode CurrentMode();

// Записать выбор. Возвращает false, если файл не удалось создать.
bool SaveMode(DecodeMode mode);

// Итоговый ответ для декодера: разворачивает Auto в да/нет.
//
// Auto опирается на замер, а не на здравый смысл: аппаратное декодирование
// оказалось МЕДЛЕННЕЕ программного (1440p: 130 против 800 кадров/с), потому что
// Premiere нужны кадры в обычной памяти и за видеокарту приходится платить
// копированием из неё. Но dav1d раскладывается по ядрам, и на слабом процессоре
// расклад развернётся — поэтому на многоядерных выбираем процессор, на слабых
// видеокарту. Порог грубый: проверить его на разном железе было не на чем.
bool PreferHardware();

// Отдавать ли кадры асинхронно. Путь новый и с отдельным потоком внутри чужого
// процесса, поэтому у него есть выключатель: строка `async = off` в том же
// файле настроек или переменная среды AETHER_ASYNC=0.
bool AsyncDeliveryEnabled();

// Отдавать ли кадры в родном YUV, без перевода в RGB. Хост может и не взять —
// тогда всё идёт прежним путём само собой. Выключатель на случай, если возьмёт,
// а цвет уедет: строка `yuv = off` в файле настроек или AETHER_YUV=0.
bool YuvEnabled();

// Отдавать ли ДЕСЯТИБИТНЫЕ кадры двумя плоскостями (P010).
//
// По умолчанию ВКЛЮЧЕНО: на Premiere 26 это в десятки раз быстрее BGRA16
// (около 1 мс/кадр против ~16 на 1440p). Буфер берём обычным CreatePPix
// (WriteOnly): GetPixels указатель отдаёт, а GetRowBytes врёт нулём — шаг
// считаем как width*2 и сверяем с GetSize. Если писать всё же некуда —
// в том же запросе откат на BGRA16, и до перезапуска Premiere P010 не
// предлагаем.
//
// Выключить вручную: `yuv10 = off` или AETHER_YUV10=0.
bool Yuv10Enabled();

// Для автотестов: подменить файл настроек и сбросить кэш чтения.
void SetSettingsFilePathForTests(const wchar_t* path);
void ReloadSettingsForTests();

uint32_t SnapMemoryCacheMB(uint32_t mb);
uint32_t ClampPreviewCacheMB(uint32_t mb);

} // namespace av1imp
